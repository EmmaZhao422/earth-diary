let lang = 'en';
const listeners = new Set();

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('ed-lang'); } catch {}
  const nav = (navigator.language || 'en').toLowerCase();
  lang = saved || (nav.startsWith('zh') ? 'zh' : 'en');
  document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : 'en';
  return lang;
}
export const getLang = () => lang;
export function setLang(next) {
  lang = STR[next] ? next : 'en';
  try { localStorage.setItem('ed-lang', lang); } catch {}
  document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : 'en';
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}
export const onLangChange = (fn) => listeners.add(fn);

export function t(key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}
// Pick the right language out of a {en, zh} object (used by config.js labels).
export const pick = (obj) => (obj && typeof obj === 'object' ? (obj[lang] ?? obj.en ?? '') : (obj ?? ''));

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-label]').forEach((el) => {
    const v = t(el.dataset.i18nLabel); el.setAttribute('aria-label', v); el.title = v;
  });
}

export function fmtDate(iso, opts) {
  if (!iso) return '';
  const [y, m, d] = iso.split('-').map(Number);
  const dt = new Date(y, (m || 1) - 1, d || 1);
  try {
    return new Intl.DateTimeFormat(lang === 'zh' ? 'zh-CN' : 'en-US', opts || { year: 'numeric', month: 'short', day: 'numeric' }).format(dt);
  } catch { return iso; }
}
export function fmtBytes(n) {
  if (!n) return '0 MB';
  if (n < 1024 * 1024) return Math.max(1, Math.round(n / 1024)) + ' KB';
  if (n < 1024 ** 3) return (n / 1024 / 1024).toFixed(n < 10 * 1024 * 1024 ? 1 : 0) + ' MB';
  return (n / 1024 ** 3).toFixed(1) + ' GB';
}
export function fmtKm(km) {
  const n = Math.round(km);
  return new Intl.NumberFormat(lang === 'zh' ? 'zh-CN' : 'en-US').format(n) + ' km';
}
